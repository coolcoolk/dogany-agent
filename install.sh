# catalog_entries [scope] -- print "id<TAB>display<TAB>payload_ok(0/1)" per pack.
# scope="menu" (default): the interactive/menu listing -- also applies the
#   menu_visible filter (below). scope="all": every installable row
#   regardless of menu_visible, used to validate a DOGANY_PACK_ID preset by
#   id (hidden != forbidden -- a builder-side pack stays installable by id
#   even though it does not appear in the interactive menu).
catalog_entries() {
  local scope="${1:-menu}"
  python3 - "$CATALOG_FILE" "$DOGANY_LANG" "$scope" <<'PYEOF' 2>/dev/null || true
import json, os, sys
path, lang, scope = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    cat = json.load(f)
base = os.path.dirname(os.path.abspath(path))
for p in cat.get("packs", []):
    # MINOR-2 (vocabulary updated): only 'published' packs list in the public
    # installer menu. Contract vocabulary (compat-lint.sh D-D gate, DGN-783
    # B3): scaffold -> draft -> published; 'retired' rows stay excluded.
    # 'official' is the pre-DGN-783 legacy spelling of published -- the
    # install-side D-D signature gate refuses any status != 'published', so
    # listing a legacy/draft row would be list-then-fail-install.
    if p.get("status") != "published":
        continue
    # Kits (kind == 'kit', e.g. lifekit) are activated post-mint via
    # pack_install.sh onto an existing agent -- they are never minted AS a
    # domain agent (catalog lifekit row note, DGN-803 LS-5) and carry no
    # role_prose, so a kit row in this menu would crash the mint flow.
    # NB: 'kind' is a load-bearing manifest-contract class switch elsewhere
    # (compat-lint.sh C-KIND, pack_install.sh dispatch -- exactly 'kit' or
    # 'pack', nothing else); it is NOT reused for menu visibility below.
    if p.get("kind") == "kit":
        continue
    # menu_visible (optional bool per row, default True): a dedicated
    # installer-MENU-listing flag, orthogonal to status/kind/deploy_owner.
    # Builder-side packs (tooling to build agents WITH, never an end-user
    # domain-agent choice -- e.g. 'dev', a stateless discipline-script pack;
    # owner decision 2026-08-23, DGN-1049 SS3 open item) set
    # menu_visible=false to drop out of the interactive "domain agent" menu
    # while staying installable by id (scope="all" below). Absent field =
    # visible: a pack with no opinion behaves exactly as before this field
    # existed -- it never silently vanishes from the menu.
    if scope == "menu" and p.get("menu_visible") is False:
        continue
    pid = p.get("id", "")
    # MINOR-1 (i18n DGN-210): en install prefers *_en / bare fields; falls back
    # to *_ko only when the en field is absent (so a missing en field degrades
    # gracefully rather than crashing, but a present en field wins).
    if lang == "en":
        name = p.get("name_en") or p.get("name") or p.get("name_ko") or pid
        tag = p.get("tagline_en") or p.get("tagline") or p.get("tagline_ko") or ""
    else:
        name = p.get("name_ko") or pid
        tag = p.get("tagline_ko") or ""
    pkg = p.get("package_dir") or ""
    if pkg and not os.path.isabs(pkg):
        pkg = os.path.join(base, pkg)
    ok = 1 if (pkg and os.path.isfile(os.path.join(pkg, "pack-manifest.json"))) else 0
    print("%s\t%s -- %s\t%d" % (pid, name, tag, ok))
PYEOF
}

