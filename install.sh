# --- Linux package-manager ladder ---------------------------------------------
# DGN-1288 phase 2. This WAS apt_install(): auto-install worked on Debian/Ubuntu
# and returned 1 everywhere else, so a Fedora/Arch/Alpine/SUSE user was handed a
# hardcoded `apt-get` sentence their machine cannot run -- a dead end wearing the
# clothes of an instruction. One detection now derives all three things we need:
# the package NAMES, the command we RUN, and the command we PRINT when we cannot
# run it ourselves (manual_hint reuses pkg_manual_cmd, so the printed line is by
# construction the line we would have executed).
#
# The apt-get row is the pre-existing behavior verbatim -- same notice, same
# `apt-get update` at most once per install (PKG_UPDATED, was APT_UPDATED), same
# `apt-get install -y`. tests/dgn1288_pkg_ladder_selftest.sh pins that parity.
#
# Detection ORDER matters: dnf before yum, because on Fedora/RHEL8+ `yum` is a
# compat shim for dnf and naming the real tool keeps every printed line honest.
PKG_MGR=""            # apt-get | dnf | yum | pacman | zypper | apk | "" (none)
PKG_MGR_PROBED=0
PKG_UPDATED=0         # the metadata refresh runs at most ONCE per install
PKG_SUDO_NOTED=0      # the pre-sudo password notice prints at most ONCE
PKG_SUDO=""           # "sudo" or "" (already root) -- set by pkg_can_elevate

detect_pkg_mgr() {
  if [ "$PKG_MGR_PROBED" = "0" ]; then
    PKG_MGR_PROBED=1
    local m
    for m in apt-get dnf yum pacman zypper apk; do
      if command -v "$m" >/dev/null 2>&1; then PKG_MGR="$m"; break; fi
    done
  fi
  [ -n "$PKG_MGR" ]
}

# pkg_names <dep> -- package list for the DETECTED manager. Package names are
# NOT portable; each row below is a distro fact, not a guess:
#   apt-get  Debian/Ubuntu carve the stdlib venv module OUT of python3 into
#            python3-venv (pre-existing mapping, unchanged).
#   dnf/yum  Fedora/RHEL ship venv inside python3; no python3-venv package
#            exists in those repos, so asking for one FAILS the transaction.
#   pacman   Arch's interpreter package is `python` (there is no `python3`
#            package); venv is bundled.
#   zypper   openSUSE's python3 pulls python3-base, which carries venv.
#   apk      Alpine's python3 carries venv (pip lives in py3-pip, which the
#            bridge venv bootstraps for itself).
# With no manager detected we still answer with the plain, most common name so
# the dead-end message can NAME the missing package instead of hand-waving.
pkg_names() {
  case "$PKG_MGR:$1" in
    apt-get:python) printf 'python3 python3-venv' ;;
    pacman:python)  printf 'python' ;;
    *:python)       printf 'python3' ;;
    *:git)          printf 'git' ;;
  esac
}

# pkg_update_cmd -- metadata refresh for the detected manager; empty when the
# manager needs none (dnf/yum refresh their own metadata per transaction).
# pacman: `-Sy` only, never `-Syu` -- a full system upgrade is not ours to run.
pkg_update_cmd() {
  case "$PKG_MGR" in
    apt-get) printf 'apt-get update' ;;
    apk)     printf 'apk update' ;;
    zypper)  printf 'zypper --non-interactive refresh' ;;
    pacman)  printf 'pacman -Sy' ;;
  esac
}

# pkg_install_cmd -- non-interactive install command for the detected manager.
pkg_install_cmd() {
  case "$PKG_MGR" in
    apt-get) printf 'apt-get install -y' ;;
    dnf)     printf 'dnf install -y' ;;
    yum)     printf 'yum install -y' ;;
    pacman)  printf 'pacman -S --needed --noconfirm' ;;
    zypper)  printf 'zypper --non-interactive install' ;;
    apk)     printf 'apk add' ;;
  esac
}

# pkg_can_elevate -- can we run a package transaction at all? Sets PKG_SUDO to
# "sudo", or to "" when we are ALREADY root (minimal container images run as
# root and often ship no sudo binary at all). Callers must test the RETURN, not
# the emptiness of PKG_SUDO: "" is a legitimate success value.
pkg_can_elevate() {
  PKG_SUDO=""
  local uid
  uid="$(id -u 2>/dev/null || true)"
  [ "$uid" = "0" ] && return 0
  if command -v sudo >/dev/null 2>&1; then PKG_SUDO="sudo"; return 0; fi
  return 1
}

# pkg_manual_cmd <dep> -- the exact one-line command that installs <dep> on THIS
# machine, or empty (return 1) when no known manager is present. The sudo prefix
# here is about the SHELL the user will type into, so it depends only on whether
# they are root -- not on whether a sudo binary exists in ours.
pkg_manual_cmd() {
  detect_pkg_mgr || return 1
  local pfx="sudo " uid
  uid="$(id -u 2>/dev/null || true)"
  [ "$uid" = "0" ] && pfx=""
  printf '%s%s %s' "$pfx" "$(pkg_install_cmd)" "$(pkg_names "$1")"
}

# pkg_install <dep> -- auto-install one dep with the detected manager. Returns
# non-zero after ONE plain note when the distro has no manager we know or when
# we cannot become root; the caller falls back to manual_hint, which prints the
# copyable command for that same state.
pkg_install() {
  local dep="$1" upd
  if ! detect_pkg_mgr; then
    msg "  [주의] 아는 패키지 관리자를 찾지 못했습니다 (apt-get/dnf/yum/pacman/zypper/apk). 수동 설치가 필요합니다." \
        "  [NOTE] No known package manager found (apt-get/dnf/yum/pacman/zypper/apk). Manual install required."
    return 1
  fi
  if ! pkg_can_elevate; then
    msg "  [주의] 관리자 권한을 얻을 수 없습니다 (root 도 아니고 sudo 도 없음). 수동 설치가 필요합니다." \
        "  [NOTE] Cannot become root (not root, and no sudo binary). Manual install required."
    return 1
  fi
  upd="$(pkg_update_cmd)"
  # The password notice precedes the FIRST sudo of the install, exactly as the
  # apt-only version did. Managers with no refresh step get the install-worded
  # twin instead, so the notice never describes work we are not doing.
  if [ "$PKG_SUDO_NOTED" = "0" ]; then
    if [ -n "$upd" ]; then
      msg "  잠시 후 sudo 로 패키지 목록을 갱신합니다. 비밀번호 입력창이 뜰 수 있습니다." \
          "  About to refresh the package list with sudo; a password prompt may appear."
    else
      msg "  잠시 후 sudo 로 패키지를 설치합니다. 비밀번호 입력창이 뜰 수 있습니다." \
          "  About to install packages with sudo; a password prompt may appear."
    fi
    PKG_SUDO_NOTED=1
  fi
  if [ -n "$upd" ] && [ "$PKG_UPDATED" = "0" ]; then
    # Word splitting on $PKG_SUDO/$upd is deliberate: both are our OWN literals
    # from the case tables above, never user input.
    $PKG_SUDO $upd || return 1
    PKG_UPDATED=1
  fi
  $PKG_SUDO $(pkg_install_cmd) $(pkg_names "$dep") || return 1
}

