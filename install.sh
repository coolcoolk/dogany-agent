# registry_upsert <class> <root> -- add/refresh this instance's registry line.
registry_upsert() {
  local class="$1" root="$2"
  local canon; canon="$(canon_path "$root")"
  [ "$DRY_RUN" = "1" ] && return 0
  mkdir -p "$DOGANY_HOME_DIR"
  touch "$REGISTRY_FILE"
  local tmp; tmp="$(mktemp)"
