# sonnet_model_display -- the display name ("Claude Sonnet 5.5") of the model
# the sonnet alias resolves to on THIS account, or nothing. One minimal claude
# turn, the routines/cli-updater.py smoke shape (claude -p --model sonnet
# --output-format stream-json --verbose); the reported id is read and mapped by
# agents/.template/routines/lib/model_display.py, the one parser of model ids
# and reader of dispatch-model-display.tsv. Bounded by
# DOGANY_MODEL_PROBE_TIMEOUT seconds (background + poll; macOS has no
# `timeout`). Any failure prints nothing, so the caller's fallback wording
# stands -- it never blocks the install.
sonnet_model_display() {
  local lib="$REPO_ROOT/agents/.template/routines/lib/model_display.py"
  local limit="${DOGANY_MODEL_PROBE_TIMEOUT:-20}" py="${PYTHON_BIN:-python3}"
  local out pid rc waited=0 shown
  [ "$DRY_RUN" = "1" ] && return 1
  [ -f "$lib" ] || return 1
  command -v claude >/dev/null 2>&1 || return 1
  command -v "$py" >/dev/null 2>&1 || return 1
  out="$(mktemp "${TMPDIR:-/tmp}/dogany-model.XXXXXX")" || return 1
  ( cd "${TMPDIR:-/tmp}" && exec claude -p "just answer me hi" --model sonnet \
      --output-format stream-json --verbose ) >"$out" 2>/dev/null </dev/null &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    if [ "$waited" -ge "$limit" ]; then
      kill "$pid" 2>/dev/null || true
      break
    fi
    sleep 1
    waited=$((waited+1))
  done
  wait "$pid" 2>/dev/null; rc=$?
  shown=""
  if [ "$rc" = "0" ]; then
    # model_display() returns the raw id when it cannot parse one; a raw id is
    # not a display name, so only a parsed claude-* id is printed.
    shown="$("$py" -c 'import sys
sys.path.insert(0, sys.argv[1])
import model_display as m
ids = m.observe_from_stream(sys.argv[2])
mid = ids[0] if ids else ""
shown = m.model_display("claude-code", "sonnet", mid) if mid.startswith("claude-") else ""
print(shown if shown != mid else "")' "$(dirname "$lib")" "$out" 2>/dev/null || true)"
  fi
  rm -f "$out"
  [ -n "$shown" ] || return 1
  printf '%s' "$shown"
}

