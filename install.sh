#   1. uv    -- a user-local interpreter, no admin: an existing uv, else the
#               uv standalone installer (lands in ~/.local/bin), then
#               `uv python install 3.12` into ~/.dogany/python;
#               always provision before probing, including on re-install;
#   2. fail  -- the owner-language failure lines with the alternatives
#               (prereq_fail_line), the log path under them. Every installer's
#               output goes to that log, never to the screen.
# install_git uses the same log.
# Linux does not enter this ladder (pkg_install, DGN-1288).
PREREQ_INSTALL_LOG=""

# prereq_install_log -- path of the installer log, created on first use. Prefers
# ~/.dogany; falls back to TMPDIR when that is not writable.
prereq_install_log() {
  if [ -z "$PREREQ_INSTALL_LOG" ]; then
    if mkdir -p "$HOME/.dogany/logs" 2>/dev/null && [ -w "$HOME/.dogany/logs" ]; then
      PREREQ_INSTALL_LOG="$HOME/.dogany/logs/install-prereqs.log"
    else
      PREREQ_INSTALL_LOG="${TMPDIR:-/tmp}/dogany-install-prereqs.log"
    fi
    printf '=== install.sh prereqs %s ===\n' \
      "$(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true)" >>"$PREREQ_INSTALL_LOG" 2>/dev/null || true
  fi
  printf '%s' "$PREREQ_INSTALL_LOG"
}

# prereq_log_run <label> <cmd...> -- run cmd with stdout+stderr appended to the log.
# stdin is detached so an installer can never sit on a hidden prompt.
prereq_log_run() {
  local label="$1" log rc
  shift
  log="$(prereq_install_log)"
  printf -- '--- %s: %s\n' "$label" "$*" >>"$log" 2>/dev/null || true
  "$@" >>"$log" 2>&1 </dev/null
  rc=$?
  printf -- '--- %s rc=%s\n' "$label" "$rc" >>"$log" 2>/dev/null || true
  return "$rc"
}

# uv_bin -- absolute path of a usable uv (PATH first, then the standalone
# installer's default homes), or return 1.
uv_bin() {
  local u
  u="$(command -v uv 2>/dev/null || true)"
  if [ -n "$u" ] && [ -x "$u" ]; then printf '%s' "$u"; return 0; fi
  for u in "${XDG_BIN_HOME:-$HOME/.local/bin}/uv" "$HOME/.local/bin/uv" "$HOME/.cargo/bin/uv"; do
    if [ -x "$u" ]; then printf '%s' "$u"; return 0; fi
  done
  return 1
}

# Only the pinned, managed interpreter in our private install directory counts.
# No fallback to PATH, another user's uv store, or a project .venv.
uv_python_find() {
  local u p="" root
  u="$(uv_bin)" || return 1
  root="$(cd "$HOME/.dogany/python" && pwd -P)" || return 1
  p="$(cd / && env UV_PYTHON_INSTALL_DIR="$root" \
    "$u" python find --managed-python --system --no-project --resolve-links 3.12 2>/dev/null)" || return 1
  case "$p" in "$root/"*) ;; *) return 1 ;; esac
  [ -x "$p" ] || return 1
  printf '%s' "$p"
}

# install_python_local -- rung 1. uv (existing, or the standalone installer
# into ~/.local/bin) installs a user-local CPython; PY_LOCAL_BIN records its
# absolute path for probe_python.
install_python_local() {
  local u p
  if ! u="$(uv_bin)"; then
    # Official uv standalone installer: user-local, no sudo. NO_MODIFY_PATH
    # keeps it out of the user's shell profile -- we call uv by absolute path.
    # Source: https://docs.astral.sh/uv/getting-started/installation/
    prereq_log_run "uv installer" /bin/sh -c \
      'curl -LsSf https://astral.sh/uv/install.sh | env UV_NO_MODIFY_PATH=1 INSTALLER_NO_MODIFY_PATH=1 sh' \
      || return 1
    u="$(uv_bin)" || return 1
  fi
  prereq_log_run "uv python install" env UV_PYTHON_INSTALL_DIR="$HOME/.dogany/python" \
    UV_NO_MODIFY_PATH=1 "$u" python install 3.12 --no-bin || return 1
  p="$(uv_python_find)" || return 1
  PY_LOCAL_BIN="$p"
  return 0
}

install_python() {
  msg "  -> Python 3.11+ 설치 중..." "  -> Installing Python 3.11+..."
  if [ "$OS_KIND" = "macos" ]; then
    # DRAFT copy (DGN-1824, owner-gated)
    msg "  -> 사용자 전용 Python 3.12 설치 중 (uv, 관리자 권한 불필요)..." \
        "  -> Installing a user-only Python 3.12 (uv, no admin needed)..."
    if install_python_local && probe_python; then
      return 0
    fi
    prereq_fail_line python "$(prereq_install_log)"
    return 1
  else
    pkg_install python && return 0
    prereq_fail_line python
    return 1
  fi
}

