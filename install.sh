# 5b2. Claude install-method classification + owner query gate (DGN-986 [d],
# spec axis C: worklog/DGN-986-health-surface-spec-draft.md section 4/7-다).
# Separate from probe_claude() above (which only checks presence) -- this
# classifies HOW the already-present `claude` got there, so a non-native
# (npm) install can be surfaced to the owner instead of silently going stale
# (npm installs do not auto-update).
# ---------------------------------------------------------------------------

# _claude_realpath <path> -- portable symlink-chain resolver. bash 3.2 (macOS
# ships this) has no guaranteed `realpath` / `readlink -f` (see canon_path()'s
# note above), so this follows symlinks by hand via `readlink` (POSIX, no -f
# needed) up to 40 hops. A cycle or absurdly long chain stops at the hop cap
# rather than looping forever -- the caller gets the last path seen, not a
# hang. Once the chain lands on a non-symlink, the containing directory is
# normalized via canon_path (collapses . / .. / // ) and the file name is
# re-appended; this still works even if the final target does not exist
# (defensive -- `command -v` found something, but a dangling symlink's target
# might not exist).
_claude_realpath() {
  local p="$1" hops=0 target
  while [ -L "$p" ]; do
    hops=$((hops + 1))
    if [ "$hops" -gt 40 ]; then
      break   # cycle / absurd chain -- stop guessing, resolve what we have
    fi
    target="$(readlink "$p" 2>/dev/null || true)"
    [ -n "$target" ] || break
    case "$target" in
      /*) p="$target" ;;
      *) p="$(dirname "$p")/$target" ;;
    esac
  done
  printf '%s/%s' "$(canon_path "$(dirname "$p")" 2>/dev/null || dirname "$p")" "$(basename "$p")"
}

# _file_owner_uid <path> -- portable file-owner UID. macOS (BSD stat) and
# Linux (GNU stat) use different flag letters for the same field (same
# portability split already used by tests/install_smoke.sh's env_mode()).
# Empty on failure (path gone, stat missing) -- callers must treat empty as
# "ownership not confirmed", never coerce it to 0/root.
_file_owner_uid() {
  if [ "$OS_KIND" = "macos" ]; then
    stat -f '%u' "$1" 2>/dev/null || true
  else
    stat -c '%u' "$1" 2>/dev/null || true
  fi
}

# classify_claude_install -- never dies (fail-open). Sets two globals:
#   CLAUDE_INSTALL_METHOD      -- native | global | local | unknown
#   CLAUDE_INSTALL_DETECT_PATH -- resolved real path of the claude binary, or
#                                  empty when `claude` is not on PATH, or PATH
#                                  resolves to a shell function/alias rather
#                                  than a real file (command -v then prints
#                                  something that does not start with "/" --
#                                  left unresolved rather than guessed at).
# Priority (spec 4절):
#   1) ~/.claude.json's "installMethod" field. Read via a plain regex grep,
#      NOT a JSON parser -- a malformed/partially-written ~/.claude.json
#      still yields the field if that substring is intact, and yields
#      nothing (safe fallback to step 2) if the file is truly unreadable/
#      unrelated JSON.
#   2) Fallback heuristic over the realpath of `command -v claude`:
#        - under $HOME/.local/                          -> native
#        - path contains node_modules or /npm/          -> global (npm layout)
#        - under /usr/local AND file is root-owned       -> global (system npm)
#        - anything else                                 -> unknown (never
#          guess past this point -- item 5, "판별 불가 = 조용히 통과").
classify_claude_install() {
  CLAUDE_INSTALL_METHOD="unknown"
  CLAUDE_INSTALL_DETECT_PATH=""

  local cv
  cv="$(command -v claude 2>/dev/null || true)"
  case "$cv" in
    /*) CLAUDE_INSTALL_DETECT_PATH="$(_claude_realpath "$cv")" ;;
    *) : ;;   # not on PATH, or a function/alias -- nothing to resolve
  esac

  # --- 1st priority: ~/.claude.json installMethod field ---
  if [ -r "$HOME/.claude.json" ]; then
    local field
    field="$(grep -oE '"installMethod"[[:space:]]*:[[:space:]]*"[a-zA-Z_-]+"' "$HOME/.claude.json" 2>/dev/null \
              | head -n1 | grep -oE '"[a-zA-Z_-]+"$' 2>/dev/null | tr -d '"')"
    case "$field" in
      native|global|local)
        CLAUDE_INSTALL_METHOD="$field"
        return 0
        ;;
    esac
  fi

  # --- 2nd priority: realpath heuristic (field absent/unreadable/unrecognized) ---
  [ -n "$CLAUDE_INSTALL_DETECT_PATH" ] || return 0   # nothing to heuristic over -> unknown

  case "$CLAUDE_INSTALL_DETECT_PATH" in
    "$HOME/.local/"*)
      CLAUDE_INSTALL_METHOD="native"
      ;;
    *node_modules*|*/npm/*)
      CLAUDE_INSTALL_METHOD="global"
      ;;
    /usr/local/*)
      local owner_uid
      owner_uid="$(_file_owner_uid "$CLAUDE_INSTALL_DETECT_PATH")"
      [ "$owner_uid" = "0" ] && CLAUDE_INSTALL_METHOD="global"
      ;;
  esac
  return 0
}

# macOS accepts only the interpreter provisioned by this installer run.
# Linux retains its existing PATH/package-manager policy.
PY_FOUND_VER=""
PY_LOCAL_BIN=""
probe_python() {
  PYTHON_BIN=""; PY_FOUND_VER=""
  local cand ver
  if [ "$OS_KIND" = "macos" ]; then
    cand="$PY_LOCAL_BIN"
    [ -n "$cand" ] && [ -x "$cand" ] || return 1
    ver="$("$cand" -c 'import sys;print("%d.%d.%d"%sys.version_info[:3])' 2>/dev/null || true)"
    if py_version_ok "$ver"; then PYTHON_BIN="$cand"; PY_FOUND_VER="$ver"; return 0; fi
    return 1
  fi
  for cand in python3 python3.13 python3.12 python3.11; do
    if command -v "$cand" >/dev/null 2>&1; then
      ver="$("$cand" -c 'import sys;print("%d.%d.%d"%sys.version_info[:3])' 2>/dev/null || true)"
      if py_version_ok "$ver"; then PYTHON_BIN="$cand"; PY_FOUND_VER="$ver"; return 0; fi
    fi
  done
  return 1
}

# probe_git -> 0 if a working `git` is on PATH.
# macOS ships /usr/bin/git as a stub even without the Xcode Command Line Tools;
