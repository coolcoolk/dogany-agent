  awk -F'\t' -v r="$canon" '$2 != r' "$REGISTRY_FILE" > "$tmp" || true
  printf '%s\t%s\n' "$class" "$canon" >> "$tmp"
  mv "$tmp" "$REGISTRY_FILE"
}

