# record_claude_install_choice <decision> -- appends ONE record (classify +
# resolved path + owner decision + timestamp) to $HOME/.dogany/claude-install-
# choice. $HOME is read at CALL time (not sourced at file-load time) so a
# test harness that reassigns HOME before invoking this still lands in the
# right sandbox. Called for every gate outcome, including "unknown" (spec
# item 5: unknown is never QUERIED, but IS recorded so a later /health
# surface can see it).
# --dry-run: NEVER writes for real -- the file header's invariant ("all
# filesystem writes are redirected ... no live command is ever executed" in
# --dry-run) covers this real-$HOME marker file same as SINGLE_AGENT_MARKER;
# prints what would have been recorded instead (same idiom as
# check_single_agent()'s "[dry-run] Would write marker: ..." lines).
# Best-effort otherwise: a write failure here must never abort the installer
# (fail-open, same spirit as the [b] runtime-snapshot.json "never blocks
# boot" rule).
record_claude_install_choice() {
  local decision="$1" when record_file
  record_file="$HOME/.dogany/claude-install-choice"
  if [ "$DRY_RUN" = "1" ]; then
    msg "  [dry-run] 기록하지 않음 (classify=$CLAUDE_INSTALL_METHOD, decision=$decision)" \
        "  [dry-run] Not recording for real (classify=$CLAUDE_INSTALL_METHOD, decision=$decision)"
    return 0
  fi
  mkdir -p "$HOME/.dogany" 2>/dev/null || return 0
  when="$(date -u +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || true)"
  {
    printf 'classify=%s\n' "$CLAUDE_INSTALL_METHOD"
    printf 'resolved_path=%s\n' "$CLAUDE_INSTALL_DETECT_PATH"
    printf 'decision=%s\n' "$decision"
    printf 'when=%s\n' "$when"
    printf '\n'
  } >>"$record_file" 2>/dev/null || true
}

