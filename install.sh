# dgn227_postmint <root> -- A4 per-path chain, runs right after a successful
# mint: class record (keep-if-present contract is mint-side, G1), KIT anchor,
# stamp-role, lifekit.conf, pack_install (--no-start, P23), generic-brief
# explicit scheduling (domain), registry upsert. The single-agent marker write stays
# OUTSIDE this function and comes LAST (G2-3 / P28).
dgn227_postmint() {
  local target="$1"
  local class="${DOGANY_AGENT_CLASS:-main}"

  # class stamp (A4; readers with no key treat the instance as main, P13)
  conf_upsert "$target/.instance.conf" DOGANY_AGENT_CLASS "$class"

  # DGN-1539: consume-checkout opt-in. DGN-1513 delivers the mint skill through
  # a tag-pinned checkout whose advance step is a NO-OP unless this key exists,
  # and nothing seeded it -- so every fresh install was a permanent
  # non-receiver of a shipped product feature. Seed it here (owner ruling
  # 2026-09-17: seed at install). A canonical maintainer that deliberately does
  # not receive removes the key; that is two instances in this estate and an
  # explicit act, which is the right way round -- absence used to mean "never
  # told", and it now means "declined".
  conf_upsert "$target/.instance.conf" DOGANY_CONSUME_ROOT "$target/.dogany-consume"

  # DGN-590 P2-a: PLAN single-source stamp. step_model probes the subscription
  # plan slug into DOGANY_PLAN (empty when the probe failed -- P2-0 exception:
  # no code writes a plan then, and BRIDGE_MODELS stays fail-open). BRIDGE_MODELS
  # in .env derives from this same slug via plan_bridge_models.
  if [ -n "${DOGANY_PLAN:-}" ]; then
    conf_upsert "$target/config/agent.conf" PLAN "$DOGANY_PLAN"
  fi

  # DGN-466 KIT anchor (F-(b) generalized; OQ-B tristate; DGN-783 BK-1).
  # Default is class enum only (DGN-590 abolished tiers). DGN-1406 (owner
  # approved 2026-09-12) revises the DGN-590 domain rule from an absolute
  # "kitless by construction" to "kitless BY DEFAULT, unless a preset says
  # otherwise" -- see the DGN-1406 ticket record for the full note.
  #   main   -> default KIT=pending (the kit-select offer state). A main is
  #            kit-eligible; onboarding-check.py fires the kit-select offer
  #            while KIT=pending, and the chosen value (lifekit | none) is
  #            written by that onboarding step. Install seeds the pending
  #            scaffold only (OQ-A: onboarding is the value SOURCE). A main
  #            that wants no kit resolves to KIT=none at the offer (decided
  #            kitless), not at install.
  #   domain -> default KIT=none. A staff/domain instance ships kitless
  #            unless a preset overrides it (below); the key is recorded as
  #            none rather than omitted (removes the old "absent => implicit
  #            main/kit" misread). A domain is NEVER seeded pending: no
  #            interactive kit-select offer is made to it (DGN-1406 adds a
  #            non-interactive preset path only, not the offer UX).
  # DOGANY_KIT preset override (both classes, DGN-1406): when explicitly set
  # to a real kit (lifekit | bizkit) it wins over the class default -- a
  # non-interactive preset that pre-decides the kit for a main OR a domain.
  # The default (unset => "none") does NOT force none on a main; main
  # defaults to pending so the offer path stays live. On domain the unset
  # default stays "none" -- BYTE-IDENTICAL to pre-DGN-1406 behavior when no
  # preset is given (the invariant this revision must hold).
  # write-if-absent: seed only when the key is missing so a reconfigure re-run
  # never overwrites a user's chosen kit (same contract as LIFEKIT= below).
  # This anchor is the ONLY seeder: .template ships no KIT= value line
  # (FATAL-1 -- a shipped value would no-op this write-if-absent and freeze
  # the offer, the OQ-B circular defect).
  local _kit_default="none"
  [ "$class" = "main" ] && _kit_default="pending"
  local _kit_seed="$_kit_default"
  if [ -n "$DOGANY_KIT" ] && [ "$DOGANY_KIT" != "none" ]; then
    # BK-1 rider (DGN-783): whitelist -- only known valid kit names are accepted.
    # An unrecognized value (e.g. a typo) must NOT be written to agent.conf because
    # a bad KIT= value permanently freezes the instance kitless (OQ-B FATAL path).
    # Fall back to the class default so the normal offer/kitless path stays live.
    case "$DOGANY_KIT" in
      lifekit|bizkit)
        _kit_seed="$DOGANY_KIT"
        ;;
      *)
        printf '[WARN] DOGANY_KIT="%s" is not a recognised kit; falling back to KIT=%s\n' \
          "$DOGANY_KIT" "$_kit_default" >&2
        ;;
    esac
  fi
  conf_set_if_absent "$target/config/agent.conf" KIT "$_kit_seed"

  # A3/A4: role stamp on EVERY path via the single stamp machine (P15).
  # A main carries no role prose (kit-pending): only Q6 is excised.
  if [ -n "$AGENT_ROLE_PROSE" ]; then
    DOGANY_PYTHON_BIN="$PYTHON_BIN" bash "$REPO_ROOT/scripts/pack/mint_run.sh" stamp-role \
      --root "$target" --role "$AGENT_ROLE_PROSE" \
      || { msg "[에러] role 스탬프 실패" "[ERROR] role stamp failed" >&2; exit 1; }
  elif [ "$class" = "main" ]; then
    DOGANY_PYTHON_BIN="$PYTHON_BIN" bash "$REPO_ROOT/scripts/pack/mint_run.sh" stamp-role \
      --root "$target" --kit-pending \
      || { msg "[에러] role 스탬프 실패" "[ERROR] role stamp failed" >&2; exit 1; }
  fi

  if [ "$class" = "domain" ]; then
    # P3: suppress the SessionStart lifekit proposal; opt-in stays via C2.
    # MAJOR-1 (D1/G1): seed LIFEKIT=off for fresh installs, but preserve any
    # real user choice already present.  Real mint.sh scaffolds LIFEKIT=pending
    # (not absent), so conf_set_if_absent is a guaranteed NO-OP on first install.
    # Required semantics:
    #   on  -> leave (C2 opt-in preserved)
    #   off -> leave (already correct / user choice)
    #   pending | empty | absent -> force off (fresh domain = lifekit dormant)
    local _lk_conf; _lk_conf="$(kit_conf_file "$target")"
    local _lk_cur; _lk_cur="$(conf_read "$_lk_conf" LIFEKIT)"
    if [ "$_lk_cur" != "on" ] && [ "$_lk_cur" != "off" ]; then
      conf_upsert "$_lk_conf" LIFEKIT "off"
    fi

    # A4: catalog pack install (--no-start is MANDATORY -- service start is
    # owned by step_service alone, P23; fresh/standalone => no --migrate-from)
    if [ -n "$DOGANY_PACK_ID" ] && [ "$DOGANY_PACK_ID" != "blank" ]; then
      # DGN-1424: pin pack_install.sh's interpreter resolution to the SAME
      # Python check_prereqs already verified (>= 3.11), same precedent as
      # the mint.sh DOGANY_PYTHON_BIN pin below -- a bare `python3` inside
      # pack_install.sh's own resolver would re-probe PATH independently.
      # DGN-1489: this lane passes no --source-tag, so pack_install's
      # source-tag gate auto-verifies refs/tags/pack/<id>/v<manifest version>
      # in the pack source repo and REFUSES an untagged version. A deliberate
      # untagged working-tree install (dev-crew minting, rehearsal harness)
      # must declare itself via DOGANY_PACK_UNTAGGED_LOCAL="<reason>" --
      # forwarded verbatim; pack_install owns the judgement and records the
      # declaration in the install receipt (source=untagged-local:<reason>).
      # Unset/empty = no declaration, fail-closed on untagged versions.
      DOGANY_PYTHON_BIN="$PYTHON_BIN" bash "$REPO_ROOT/scripts/pack/pack_install.sh" \
        "$DOGANY_AGENT_SLUG" "$target" --pack "$DOGANY_PACK_ID" --no-start \
        ${DOGANY_PACK_UNTAGGED_LOCAL:+--untagged-local "$DOGANY_PACK_UNTAGGED_LOCAL"} \
        || { msg "[에러] 팩 설치 실패: $DOGANY_PACK_ID" \
                 "[ERROR] pack install failed: $DOGANY_PACK_ID" >&2; exit 1; }
    fi

    # E1-1/A4: explicit generic-brief scheduling (standalone default) --
    # without this a blank/pack-less domain would have zero briefings.
    schedule_deferred_briefs "$target"
  else
    # main path: LIFEKIT=pending keeps the post-onboarding lifekit proposal.
    # MAJOR-1 (write-if-absent): a reconfigure re-run must not revert a live
    # LIFEKIT=on (or explicitly off) instance back to pending.
    conf_set_if_absent "$(kit_conf_file "$target")" LIFEKIT "pending"
  fi

  # G2-3a/G3-(a): registry before marker; marker is written LAST by caller.
  registry_upsert "$class" "$target"
}

