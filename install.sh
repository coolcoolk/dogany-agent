# progress. The caller re-probes afterwards, so a false "success" is still
# caught by the re-probe -> manual-hint fallback.

# Persist independently of the running PATH: it may already contain the bin
# directory even though a fresh login shell cannot find installed commands.
persist_local_bin_path() {
  local profile login_shell="${SHELL:-}"
  case "${login_shell##*/}" in
    # macOS Terminal opens login shells; zprofile also covers zsh login on Linux.
    zsh) profile="$HOME/.zprofile" ;;
    bash)
      # Use the platform's conventional login profile, not interactive bashrc.
      if [ "$OS_KIND" = "macos" ]; then
        profile="$HOME/.bash_profile"
      else
        profile="$HOME/.profile"
      fi
      ;;
    *)
      msg "  [경고] 새 터미널에서 명령을 찾도록 자동 설정하지 못했어요." \
          "  [WARN] Could not configure command lookup in new terminals automatically." >&2
      # Non-fatal: the install itself succeeded; set -e callers must not abort.
      return 0
      ;;
  esac
  # Respect existing owner configuration, including equivalent PATH syntax.
  if [ -f "$profile" ] && grep -qF '.local/bin' "$profile"; then
    return 0
  fi
  if [ "$DRY_RUN" = "1" ]; then
    msg "  [dry-run] 새 터미널에서 명령을 찾는 설정은 변경하지 않았어요." \
        "  [dry-run] Command lookup in new terminals was left unchanged."
    return 0
  fi
  # Append only; the initial newline preserves a last line without a newline.
  if ! printf '\n%s\n%s\n%s\n' \
      '# BEGIN Dogany local bin PATH' \
      'export PATH="$HOME/.local/bin:$PATH"' \
      '# END Dogany local bin PATH' >> "$profile"; then
    msg "  [경고] 새 터미널에서 명령을 찾는 설정을 저장하지 못했어요." \
        "  [WARN] Could not save command lookup settings for new terminals." >&2
    return 0
  fi
  msg "  새 터미널에서도 설치한 명령을 찾을 수 있도록 설정했어요." \
      "  Configured new terminals to find installed commands."
}

install_claude() {
  if [ "$DRY_RUN" = "1" ]; then
    persist_local_bin_path
    return $?
  fi
  msg "  -> Claude Code CLI 설치 중..." "  -> Installing Claude Code CLI..."
  # Officially recommended native installer for macOS AND Linux/WSL.
  # Verified 2026-07-05 at https://code.claude.com/docs/en/setup
  # (native installer script; npm is only an alternative). Binary lands in
  # ~/.local/bin; auto-updates in the background.
  curl -fsSL https://claude.ai/install.sh | bash || return 1
  # PATH pickup in THIS shell: the native installer drops the binary in
  # ~/.local/bin, which is often not yet on PATH in the running shell.
  if ! command -v claude >/dev/null 2>&1; then
    if [ -x "$HOME/.local/bin/claude" ]; then
      case ":$PATH:" in *":$HOME/.local/bin:"*) : ;; *) PATH="$HOME/.local/bin:$PATH"; export PATH ;; esac
    fi
  fi
  command -v claude >/dev/null 2>&1 || return 1
  persist_local_bin_path
}

