# ---------------------------------------------------------------------------
# 1. Bilingual string helper (inline; NOT a full i18n system by design)
# ---------------------------------------------------------------------------
# Usage: msg "korean text" "english text"  -> echoes the one matching $DOGANY_LANG.
msg() {
  if [ "${DOGANY_LANG:-en}" = "ko" ]; then
    printf '%s\n' "$1"
  else
    printf '%s\n' "$2"
  fi
}

# Same but no trailing newline (for prompts).
msgn() {
  if [ "${DOGANY_LANG:-en}" = "ko" ]; then
    printf '%s' "$1"
  else
    printf '%s' "$2"
  fi
}

hr() { printf '%s\n' "------------------------------------------------------------"; }

# ko_has_batchim <word> -- 0 when the Korean reading of <word>'s last syllable
# ends in a consonant (object particle eul), 1 otherwise (reul). For the ASCII
# item labels install.sh prints: a trailing " (...)" and trailing symbols are
# dropped ("Python 3.11+" -> "3.11"), then digits read as Sino-Korean numbers,
# an all-caps token as letter names (CLI -> ...ai), and a word by its final
# letter sound (git -> git-eul, claude -> reul). Callers pick the particle
# with msgn so the Korean stays inside msg args.
ko_has_batchim() {
  local w="${1%% (*}" tok
  while [ -n "$w" ]; do
    case "$w" in *[A-Za-z0-9]) break ;; esac
    w="${w%?}"
  done
  [ -n "$w" ] || return 1
  tok="${w##* }"
  case "$tok" in
    *[013678]) return 0 ;;
    *[0-9]) return 1 ;;
  esac
  case "$tok" in
    *[a-z]*) ;;
    *) case "$tok" in *[LMNR]) return 0 ;; *) return 1 ;; esac ;;
  esac
  case "$tok" in
    *[Nn][Gg]|*[LlMmNnKkTtPpBbCc]) return 0 ;;
  esac
  return 1
}

# ---------------------------------------------------------------------------
# 1b. Single-agent idempotency helpers
# ---------------------------------------------------------------------------
# Portable path canonicalization for bash 3.2 (macOS ships bash 3.2; no
# realpath/readlink -f guaranteed). Strategy:
#   - If the directory already exists: cd into it and capture $PWD (resolves
#     symlinks the shell follows, and normalises . / .. / trailing slashes).
#   - Otherwise: normalize trailing slashes and collapse /./ sequences via sed.
#     This covers the "pre-creation" path (install to a not-yet-existing dir).
canon_path() {
  local p="$1"
  # Expand a literal quoted tilde ("~/x" arrives verbatim when quoted).
  case "$p" in "~/"*) p="$HOME/${p#\~/}" ;; "~") p="$HOME" ;; esac
  # Relative paths anchor at the caller's cwd (a relative --root under a
  # TCC-gated cwd must still resolve into the gated tree).
  case "$p" in /*) : ;; *) p="$PWD/$p" ;; esac
  if [ -d "$p" ]; then
    (cd "$p" && pwd -P)   # physical: resolves symlinks and case (APFS)
  else
    # Not yet created: physically resolve the deepest existing ancestor,
    # then re-append the tail.
    local dir="$p" tail=""
    while [ ! -d "$dir" ] && [ "$dir" != "/" ]; do
      tail="/$(basename "$dir")$tail"
      dir="$(dirname "$dir")"
    done
    printf '%s%s' "$(cd "$dir" && pwd -P)" "$tail" \
      | sed -E 's|/+$||; s|/+|/|g; s|/\./|/|g'
  fi
}

# Dual-accept minted-instance detector (DGN-773 T3, AGENT.md -> PROFILE.md
# rename migration). A minted instance carries PROFILE.md (2.0+) or AGENT.md
# (pre-2.0); post-rename AGENT.md becomes a compat symlink to PROFILE.md
# (DGN-773 R7, 1-version window) so plain "-f AGENT.md" still sees it as
# present -- this helper additionally accepts a directly-present PROFILE.md
# with no AGENT.md at all (the eventual post-2.1-teardown shape). Every
# "is this dir a real minted instance" check in this file must route through
# here instead of hardcoding AGENT.md, so pre-2.0 and 2.0+ instances resolve
# identically.
has_persona_md() {
  # Three-way dual-accept, newest layout first (mirror of
  # scripts/pack/lib/persona_resolver.sh and routines/onboarding-check.py):
  #   identity/hot.custom.agent.md  2.0 layout (DGN-1141 stage 6)
  #   PROFILE.md                    2.0 flat root (DGN-773 T3)
  #   AGENT.md                      pre-2.0
  # A relaid-out instance carries only the first one, so an older two-name
  # check reads a live, fully-configured instance as "not an instance".
  local dir="$1"
  [ -f "$dir/identity/hot.custom.agent.md" ] \
    || [ -f "$dir/PROFILE.md" ] || [ -f "$dir/AGENT.md" ]
}

# Single-agent idempotency: at most ONE installed instance by default.
# Call before minting. Exits non-zero if a different VALID instance already
# holds the marker. Returns 0 if mint should proceed (no conflict, same root, or
# a stale marker that was self-healed).
check_single_agent() {
  local current_root="$1"
  local current_canon
  current_canon="$(canon_path "$current_root")"

  # Config knob: a non-1 limit bypasses the single-agent refusal.
  # DGN-227 G2-1: the persisted ledger (~/.dogany/config) is read when the
  # env override is unset -- the main-add flow writes the ledger so the
  # relaxation survives across runs ("no multi without an explicit user act").
  if [ "$(effective_max_agents)" != "1" ]; then
    return 0
  fi

  # --- marker absent -> no prior install -> proceed ---
  if [ ! -f "$SINGLE_AGENT_MARKER" ]; then
    if [ "$DRY_RUN" = "1" ]; then
      msg "[dry-run] lite_instance 마커 없음 -> 신규 설치 진행 예정" \
          "[dry-run] lite_instance marker absent -> would proceed with new install"
      msg "[dry-run] 마커 쓸 위치: $SINGLE_AGENT_MARKER (내용: $current_canon)" \
          "[dry-run] Would write marker: $SINGLE_AGENT_MARKER (content: $current_canon)"
    fi
    return 0
  fi

  # --- marker present but empty / malformed -> warn, treat as absent ---
  local recorded
  recorded="$(cat "$SINGLE_AGENT_MARKER" 2>/dev/null | tr -d '[:space:]')"
  if [ -z "$recorded" ]; then
    msg "[경고] lite_instance 마커가 비어 있거나 손상되었습니다. 없는 것으로 처리합니다." \
        "[WARN] lite_instance marker is empty or malformed. Treating as absent."
    if [ "$DRY_RUN" = "1" ]; then
      msg "[dry-run] 마커 쓸 위치: $SINGLE_AGENT_MARKER (내용: $current_canon)" \
          "[dry-run] Would write marker: $SINGLE_AGENT_MARKER (content: $current_canon)"
    fi
    return 0
  fi

  # --- DGN-145: recorded root missing OR not a minted instance -> stale marker,
  # self-heal (warn, drop the marker, CONTINUE the install). A minted instance
  # always carries a PROFILE.md or AGENT.md (dual-accept, DGN-773 T3); the
  # absence of both means the marked path is not a real instance
  # (moved/deleted/leftover), so it must not block a fresh install.
  if [ ! -d "$recorded" ] || ! has_persona_md "$recorded"; then
    msg "[경고] 기록된 설치 경로가 유효한 인스턴스가 아닙니다: $recorded. 오래된 마커를 제거하고 신규 설치로 계속합니다." \
        "[WARN] Recorded install path is not a valid instance: $recorded. Removing the stale marker and continuing with a new install." >&2
    [ "$DRY_RUN" = "1" ] || rm -f "$SINGLE_AGENT_MARKER" 2>/dev/null || true
    return 0
  fi

  local recorded_canon
  recorded_canon="$(canon_path "$recorded")"

  # --- same root -> reconfigure of existing single agent -> proceed ---
  if [ "$recorded_canon" = "$current_canon" ]; then
    msg "기존 에이전트를 재설정합니다: $recorded_canon" \
        "Reconfiguring existing agent: $recorded_canon"
    return 0
  fi

  # --- DGN-227 G2: existing instance is a DOMAIN agent -> offer the 3-way
  # main-add choice instead of the flat refusal. Env preset
  # DOGANY_MAIN_ADD_CHOICE=1|2|3 covers the non-interactive path (rehearsal
  # note: the spec defines no env preset for this prompt -- OPEN QUESTION).
  if [ "$(instance_class_of "$recorded_canon")" = "domain" ]; then
    local choice="${DOGANY_MAIN_ADD_CHOICE:-}"
    if [ -z "$choice" ]; then
      if [ "$DRY_RUN" = "1" ] || [ ! -t 0 ]; then
        choice=3   # no preset, non-interactive -> cancel (safe default)
      else
        local g1 g2 g3
        g1="$(msgn "그 에이전트를 재설정한다 (--root 재지정 안내, 현행 동작)" \
                   "Reconfigure that agent (rerun with --root, current behavior)")"
        g2="$(msgn "메인 에이전트를 추가한다 (멀티 에이전트로 전환)" \
                   "Add a main agent (switch to multi-agent)")"
        g3="$(msgn "취소" "Cancel")"
        select_menu "$(msgn "도메인 에이전트가 이미 있습니다: $recorded_canon" \
                           "A domain agent already exists: $recorded_canon")" \
                    2 "$g1" "$g2" "$g3"
        choice=$((SELECT_RESULT + 1))
      fi
    fi
    case "$choice" in
      2)
        # G2 step 1: explicit, persisted limit relaxation + flow arming.
        MAIN_ADD_FLOW=1
        EXISTING_DOMAIN_ROOT="$recorded_canon"
        if [ "$DRY_RUN" != "1" ]; then
          local cur_reg; cur_reg="$(wc -l < "$REGISTRY_FILE" 2>/dev/null | tr -d ' ' || true)"
          [ -n "$cur_reg" ] && [ "$cur_reg" -ge 1 ] || cur_reg=1
          conf_upsert "$GLOBAL_CONF" DOGANY_MAX_AGENTS "$((cur_reg + 1))"
          # ensure the existing domain instance is in the registry
          registry_upsert "domain" "$recorded_canon"
        fi
        msg "메인 에이전트 추가 플로우로 진행합니다 (한도 완화 기록됨)." \
            "Proceeding with the main-add flow (limit relaxation recorded)."
        return 0
        ;;
      1)
        : # fall through to the current refusal text (points at --root)
        ;;
      *)
        msg "설치를 취소했습니다." "Install cancelled." >&2
        exit 2
        ;;
    esac
  fi

  # --- DGN-145: a valid instance already exists at a different path -> stop and
  # point the user at the reset command. No tier language, no upsell.
  hr >&2
  msg "에이전트 인스턴스가 이미 존재합니다: $recorded_canon" \
      "An agent instance already exists at: $recorded_canon" >&2
  msg "해당 인스턴스를 초기화하려면 그 경로를 --root 로 지정해 다시 실행하세요:" \
      "To reset it, rerun with --root pointing at that path:" >&2
  printf '  bash install.sh --root "%s"\n' "$recorded_canon" >&2
  hr >&2
  exit 2
}

