# DGN-1286 item4: print the pending claim code for the freshly minted instance.
#
# The installer collects no owner id any more, so ALLOWED_USER_IDS is empty and
# the bridge boots into MODE_CLAIM: the first user to send '/claim <code>' owns
# the bot. The code is written by the bridge at boot to
# <root>/.telegram_bot/claim_code (and echoed to stdout + the service log), but
# the installer cannot depend on the bot having booted yet -- launchd bootstrap
# is async, and in "manual" service mode nothing has been started at all. So we
# call the bridge's OWN ownership.ensure_claim_code(), which is idempotent: it
# returns an already-written code if the bot beat us to it, otherwise it writes
# the one the bot will later reuse. Either way the installer and the bot name
# the SAME code.
#
# Both modules are loaded BY PATH, not as the `bridge` package: ownership.py and
# i18n/{ko,en}.py are stdlib-only, so this needs no venv and no bridge import
# chain (config.py would pull pydantic).
#
# The printed sentence is the bridge's approved i18n string (claim_code_log) in
# the install language -- deliberately NOT new installer copy.
#
# Silent no-op (returns non-zero, prints nothing) when: dry-run; the instance
# has no bridge; or ownership resolution says this instance is NOT in claim mode
# (an already-claimed / owner.lock / authoritative-ids instance must never be
# handed a bogus code by a re-run of the installer).
print_claim_code_line() {
  # Dry-run must not write into a real instance dir; it never mints a bridge.
  [ "$DRY_RUN" = "1" ] && return 1
  [ -f "$INSTALL_ROOT/bridge/ownership.py" ] || return 1
  python3 - "$INSTALL_ROOT" "$DOGANY_LANG" <<'PYEOF' 2>/dev/null
import importlib.util
import sys
from pathlib import Path

root, lang = Path(sys.argv[1]), sys.argv[2]
data_dir = root / ".telegram_bot"


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


try:
    own = load("dogany_ownership", root / "bridge" / "ownership.py")
    # ALLOWED_USER_IDS as mint rendered it; empty list == claim mode candidate.
    ids = []
    for line in (data_dir / ".env").read_text(encoding="utf-8").splitlines():
        if line.startswith("ALLOWED_USER_IDS="):
            ids = [int(t) for t in line.split("=", 1)[1].split(",") if t.strip().isdigit()]
    mode, _owner = own.resolve_owner(ids, data_dir)
    if mode != own.MODE_CLAIM:
        sys.exit(1)
    # Owner 2026-10-02: the finale prints the claim line itself; this
    # helper returns only the code.
    print(own.ensure_claim_code(data_dir))
except Exception:
    sys.exit(1)
PYEOF
}

